alter table room_types
  add column label_en       text not null default '' check (length(label_en) <= 80),
  add column building       text not null default '' check (length(building) <= 40),
  add column location       text not null default '' check (length(location) <= 120),
  add column area_m2        numeric(5,1) check (area_m2 is null or area_m2 between 5 and 500),
  add column price_fcfa     integer check (price_fcfa is null or price_fcfa between 0 and 10000000),
  add column extra_bed_fcfa integer check (extra_bed_fcfa is null or extra_bed_fcfa between 0 and 10000000),
  add column description_fr text not null default '' check (length(description_fr) <= 1000),
  add column description_en text not null default '' check (length(description_en) <= 1000),
  add column position       smallint not null default 0;

create table amenities (
  key      text primary key check (key ~ '^[a-z0-9_]{1,40}$'),
  label_fr text not null check (length(label_fr) between 1 and 80),
  label_en text not null default '' check (length(label_en) <= 80),
  position smallint not null default 0
);

create table room_type_amenities (
  room_type_id bigint not null references room_types(id) on delete cascade,
  amenity_key  text not null references amenities(key) on delete cascade,
  value        text not null check (value in ('oui','non','sur_demande','supplement','a_verifier')),
  primary key (room_type_id, amenity_key)
);

